#!/bin/bash
# Build: ./build.sh [debug|release|offline]      (default: release)
#   debug    debuggable, logger and QA/demo hooks ON.
#   release  silent, minimal; has the INTERNET permission (weather, posters; both off or opt-in).
#   offline  release WITHOUT the INTERNET permission: the OS blocks every socket. Provable privacy.
# Needs: JDK 17+, Android SDK (build-tools + platforms;android-34), python3, zip.
# Env (all optional):
#   ANDROID_SDK_ROOT  SDK folder (or ANDROID_HOME)      BUILD_TOOLS  version folder (default: newest)
#   PLATFORM          default android-34                 ANDROID_JAR  explicit android.jar
#   SHANGOS_JDK          JDK home                           SHANGOS_GREETING  default greeting on Home
#   SHANGOS_KEYSTORE, SHANGOS_KS_PASS, SHANGOS_KEY_ALIAS  release signing (see README "Signing")
set -euo pipefail
cd "$(dirname "$0")"
VARIANT="${1:-release}"
case "$VARIANT" in debug|release|offline) ;; *) echo "usage: $0 [debug|release|offline]"; exit 2;; esac

[ -n "${SHANGOS_JDK:-}" ] && { export JAVA_HOME="$SHANGOS_JDK"; export PATH="$JAVA_HOME/bin:$PATH"; }
command -v javac >/dev/null || { echo "javac not found: install JDK 17 or set SHANGOS_JDK"; exit 1; }

SDK="${ANDROID_SDK_ROOT:-${ANDROID_HOME:-}}"
BT=""
if [ -n "$SDK" ] && [ -d "$SDK/build-tools" ]; then
    BUILD_TOOLS="${BUILD_TOOLS:-$(ls "$SDK/build-tools" | sort -V | tail -1)}"
    BT="$SDK/build-tools/$BUILD_TOOLS"
fi
PLATFORM="${PLATFORM:-android-34}"
ANDROID_JAR="${ANDROID_JAR:-${SDK:+$SDK/platforms/$PLATFORM/android.jar}}"
[ -f "${ANDROID_JAR:-/nonexistent}" ] || { echo "android.jar not found. Set ANDROID_SDK_ROOT (needs platforms;$PLATFORM) or ANDROID_JAR."; exit 1; }
# Resolve a build tool: explicit env override, then the SDK build-tools folder, then PATH.
tool() { local var="$1" name="$2"; local v="${!var:-}"
    if [ -n "$v" ]; then echo "$v"; elif [ -n "$BT" ] && [ -x "$BT/$name" ]; then echo "$BT/$name"
    elif command -v "$name" >/dev/null; then command -v "$name"; else echo ""; fi; }
AAPT2="$(tool AAPT2 aapt2)"; ZIPALIGN="$(tool ZIPALIGN zipalign)"; APKSIGNER="$(tool APKSIGNER apksigner)"; D8="$(tool D8 d8)"
for t in AAPT2 ZIPALIGN APKSIGNER; do [ -n "${!t}" ] || { echo "missing build tool: $t (install SDK build-tools)"; exit 1; }; done
DX=""; [ -z "$D8" ] && DX="$(command -v dalvik-exchange || true)"
[ -n "$D8" ] || [ -n "$DX" ] || { echo "missing d8 (SDK build-tools) and dalvik-exchange"; exit 1; }

# Version: VERSION file -> manifest copy.
. ./VERSION
DEBUG=false; NETWORK=true
[ "$VARIANT" = debug ] && DEBUG=true
[ "$VARIANT" = offline ] && NETWORK=false
PKG="$(sed -n 's/.*package="\([^"]*\)".*/\1/p' AndroidManifest.xml | head -1)"
OUT="build/$VARIANT"; rm -rf "$OUT"; mkdir -p "$OUT/classes" "$OUT/dex" "$OUT/gen/${PKG//.//}" "$OUT/overlay/values" dist

# Flavor constants: javac folds them, so disabled branches vanish from the DEX.
cat > "$OUT/gen/${PKG//.//}/Flavor.java" <<JAVA
package $PKG;
/** Generated by build.sh. DEBUG enables QA hooks and the logger; NETWORK is false in the offline variant. */
final class Flavor { static final boolean DEBUG=$DEBUG, NETWORK=$NETWORK; private Flavor(){} }
JAVA

# Manifest copy per variant.
sed -e "s/android:versionCode=\"[0-9]*\"/android:versionCode=\"$versionCode\"/" \
    -e "s/android:versionName=\"[^\"]*\"/android:versionName=\"$versionName\"/" AndroidManifest.xml > "$OUT/AndroidManifest.xml"
if [ "$NETWORK" = false ]; then sed -i '/android.permission.INTERNET/d' "$OUT/AndroidManifest.xml"; fi

# The Home greeting: SHANGOS_GREETING, else the first line of .local/greeting.txt, else "Hello".
GREETING="${SHANGOS_GREETING:-$(head -n 1 .local/greeting.txt 2>/dev/null || true)}"; GREETING="${GREETING:-Hello}"
python3 - "$GREETING" > "$OUT/overlay/values/greeting.xml" <<'PY'
import sys, html
text = html.escape(sys.argv[1], quote=False)
for raw, escaped in (("\\", "\\\\"), ("'", "\\'"), ('"', '\\"'), ("@", "\\@"), ("?", "\\?")):
    text = text.replace(raw, escaped)
print('<resources><string name="greeting">' + text + '</string></resources>')
PY

"$AAPT2" compile --dir res -o "$OUT/resources.zip"
"$AAPT2" compile --dir "$OUT/overlay" -o "$OUT/overlay.zip"
LINK_FLAGS=(); [ "$DEBUG" = true ] && LINK_FLAGS+=(--debug-mode)
"$AAPT2" link -o "$OUT/resources.apk" -I "$ANDROID_JAR" --manifest "$OUT/AndroidManifest.xml" \
    --java "$OUT/generated" --auto-add-overlay "${LINK_FLAGS[@]}" "$OUT/resources.zip" -R "$OUT/overlay.zip"
find src "$OUT/gen" "$OUT/generated" -name '*.java' > "$OUT/sources.txt"
JAVAC_FLAGS=(-encoding UTF-8 --release 8 -Xlint:-options -Xlint:deprecation -Xlint:unchecked -classpath "$ANDROID_JAR" -d "$OUT/classes")
[ "$DEBUG" = true ] && JAVAC_FLAGS+=(-g) || JAVAC_FLAGS+=(-g:none)
javac "${JAVAC_FLAGS[@]}" @"$OUT/sources.txt" 2> "$OUT/javac.log" || { cat "$OUT/javac.log" >&2; exit 1; }  # warnings are kept for tools/audit.sh
if [ -n "$D8" ]; then
    D8_FLAGS=(--lib "$ANDROID_JAR" --min-api 31 --output "$OUT/dex"); [ "$DEBUG" = false ] && D8_FLAGS+=(--release)
    find "$OUT/classes" -name '*.class' > "$OUT/classes.txt"; "$D8" "${D8_FLAGS[@]}" @"$OUT/classes.txt"
else
    echo "note: d8 not found, using dalvik-exchange (fine for Java 8 bytecode)" >&2
    "$DX" --dex --min-sdk-version=26 --output="$OUT/dex/classes.dex" "$OUT/classes"
fi
cp "$OUT/resources.apk" "$OUT/unsigned.apk"
(cd "$OUT/dex" && zip -q -X -u ../unsigned.apk classes.dex)
"$ZIPALIGN" -f -p 4 "$OUT/unsigned.apk" "$OUT/aligned.apk"

# Signing. A dev key is created on first use with a random password kept in .signing/ (git-ignored).
# A real release key is supplied through the environment, never stored in this script.
if [ -n "${SHANGOS_KEYSTORE:-}" ]; then
    KS="$SHANGOS_KEYSTORE"; ALIAS="${SHANGOS_KEY_ALIAS:-shangos}"
    [ -n "${SHANGOS_KS_PASS:-}" ] || { read -r -s -p "Keystore password: " SHANGOS_KS_PASS; echo; }
    PASS_ARGS=(--ks "$KS" --ks-pass env:SHANGOS_KS_PASS --ks-key-alias "$ALIAS")
    SIGNER="release key"
else
    mkdir -p .signing; KS=.signing/dev.keystore
    if [ ! -f "$KS" ]; then
        head -c 18 /dev/urandom | base64 | tr -d '/+=\n' > .signing/dev.pass; chmod 600 .signing/dev.pass
        DP="$(cat .signing/dev.pass)"
        keytool -genkeypair -keystore "$KS" -storepass "$DP" -keypass "$DP" -alias shangos-dev -keyalg RSA -keysize 3072 \
            -validity 10000 -dname 'CN=shangOS dev, O=Local build' >/dev/null 2>&1
    fi
    export DEV_PASS="$(cat .signing/dev.pass)"
    PASS_ARGS=(--ks "$KS" --ks-pass env:DEV_PASS --ks-key-alias shangos-dev)
    SIGNER="DEV key (local builds only; set SHANGOS_KEYSTORE for a release)"
fi
APK="dist/shangos-$VARIANT.apk"
"$APKSIGNER" sign "${PASS_ARGS[@]}" --out "$APK" "$OUT/aligned.apk"
"$APKSIGNER" verify "$APK"
echo "Built $APK  ($(du -h "$APK" | cut -f1), signed with $SIGNER, version $versionName/$versionCode, variant $VARIANT)"
