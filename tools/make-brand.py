#!/usr/bin/env python3
"""Writes the Android launcher icon (adaptive: background, foreground, monochrome) and the Android TV banner as vector drawables
from the brand artwork in docs/assets (logo.svg = icon, banner.svg = TV banner; both written by tools/brand-art.py). One artwork, two outputs: the website and the app.
Run from the repo root:  python3 tools/make-brand.py
Files written (res/drawable): app_icon_background.xml, app_icon_foreground.xml, app_icon_monochrome.xml, app_banner.xml
mipmap-anydpi/app_icon.xml already points at the three icon layers; AndroidManifest.xml points android:banner at app_banner."""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
RES, ART = ROOT / "res" / "drawable", ROOT / "docs" / "assets"
NS = 'xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"'
NOTE = "<!-- Generated by tools/make-brand.py from docs/assets/logo.svg and banner.svg: do not edit by hand. -->"


def paths(svg):
    return re.findall(r'<path d="([^"]+)"', svg)


icon = paths((ART / "logo.svg").read_text())      # [tile clip, play, os, tile outline]
banner = paths((ART / "banner.svg").read_text())  # [word, badge, os]
if len(icon) != 4 or len(banner) != 3:
    sys.exit("unexpected artwork: run tools/brand-art.py first (logo.svg needs 4 paths, banner.svg 3)")
PLAY, OS = icon[1], icon[2]
WORD, BADGE, BADGE_OS = banner

# The mark's centre in the artwork (256 space) and the size we give it in the 108dp layer.
# Android's safe zone is the centre 66dp and a logo should be 48 to 66dp: 56dp leaves room for every mask shape.
CX, CY, SPAN, TARGET = 125.17, 106.67, 72.35, 56.0
K = TARGET / SPAN
MARK = f'android:pivotX="{CX}" android:pivotY="{CY}" android:scaleX="{K:.4f}" android:scaleY="{K:.4f}" android:translateX="{54 - CX:.3f}" android:translateY="{54 - CY:.3f}"'


def write(name, body):
    (RES / name).write_text(f'<?xml version="1.0" encoding="utf-8"?>\n{NOTE}\n{body}\n', encoding="utf-8")
    print("wrote", f"res/drawable/{name}")


def vector(w, h, inner):
    return f'<vector {NS} android:width="{w}dp" android:height="{h}dp" android:viewportWidth="{w}" android:viewportHeight="{h}">\n{inner}</vector>'


def fill_linear(x1, y1, x2, y2, stops):
    items = "".join(f'<item android:offset="{o}" android:color="{c}"/>' for o, c in stops)
    return f'<aapt:attr name="android:fillColor"><gradient android:startX="{x1}" android:startY="{y1}" android:endX="{x2}" android:endY="{y2}" android:type="linear">{items}</gradient></aapt:attr>'


def fill_radial(cx, cy, r, stops):
    items = "".join(f'<item android:offset="{o}" android:color="{c}"/>' for o, c in stops)
    return f'<aapt:attr name="android:fillColor"><gradient android:centerX="{cx}" android:centerY="{cy}" android:gradientRadius="{r}" android:type="radial">{items}</gradient></aapt:attr>'


# ---- adaptive icon: 108 x 108dp layers --------------------------------------------------------
write("app_icon_background.xml", vector(108, 108, f'''    <path android:pathData="M0,0h108v108h-108z">{fill_linear(0, 0, 0, 108, [(0, "#FF40552E"), (1, "#FF27341D")])}</path>
    <path android:pathData="M0,0h108v108h-108z" android:fillColor="#0AFFFFFF"/>
'''))
write("app_icon_foreground.xml", vector(108, 108, f'''    <group {MARK}>
        <path android:pathData="{PLAY}">{fill_linear(CX, 70, CX, 143, [(0, "#FFE6F4C6"), (1, "#FFC3DC9D")])}</path>
        <path android:pathData="{PLAY}" android:strokeColor="#4DFFFFFF" android:strokeWidth="1.2"/>
        <path android:pathData="{OS}" android:fillColor="#FF1C2911"/>
    </group>
'''))
# Themed icon (Android 13+): ONE layer, the system tints it. The "os" is cut out of the play shape (even-odd) so it shows the tint's background.
write("app_icon_monochrome.xml", vector(108, 108, f'''    <group {MARK}>
        <path android:pathData="{PLAY} {OS}" android:fillType="evenOdd" android:fillColor="#FFFFFFFF"/>
    </group>
'''))

# ---- Android TV banner: 320 x 180dp (16:9), cropped from the 895 x 495 artwork to its 760 x 427.5 panel ----
S = 320 / 760
write("app_banner.xml", vector(320, 180, f'''    <group android:scaleX="{S:.5f}" android:scaleY="{S:.5f}" android:translateX="{-67.5 * S:.3f}" android:translateY="{-33.75 * S:.3f}">
        <path android:pathData="M67.5,33.75h760v427.5h-760z">{fill_linear(67.5, 33.75, 67.5, 461.25, [(0, "#FF40552E"), (1, "#FF27341D")])}</path>
        <group android:scaleY="0.5625" android:translateY="{247.5 * (1 - 0.5625):.3f}">
            <path android:pathData="M67.5,-400h760v1400h-760z">{fill_radial(447.5, 247.5, 418, [(0, "#29E6F4C6"), (0.5, "#0DE6F4C6"), (1, "#00E6F4C6")])}</path>
        </group>
        <path android:pathData="{WORD}" android:fillColor="#FFE6F4C6"/>
        <path android:pathData="{BADGE}" android:fillColor="#FFC3DC9D"/>
        <path android:pathData="{BADGE}" android:strokeColor="#4DFFFFFF" android:strokeWidth="1"/>
        <path android:pathData="{BADGE_OS}" android:fillColor="#FF1C2911"/>
    </group>
'''))
