// Writes res/raw/cities.txt: the cities shangOS offers in Settings, City (and in setup), so the weather needs no location lookup.
//
// The data is not written here: it is GeoNames (https://www.geonames.org, CC BY 4.0), as packaged by the community npm package
// all-the-cities (MIT). Run it again to pick up newer data:
//
//   npm install --prefix /tmp/atc all-the-cities
//   node tools/cities.js /tmp/atc/node_modules/all-the-cities [minimum population, default 15000]
//
// One line per city, largest first: name|country code|admin code|latitude|longitude|population
const fs = require('fs');
const path = require('path');
const source = path.resolve(process.argv[2] || 'node_modules/all-the-cities');
const minimum = parseInt(process.argv[3] || '15000', 10);
const cities = require(source);
// Towns and cities only: no sections of a city, historical, destroyed or abandoned places.
const excluded = new Set(['PPLX', 'PPLH', 'PPLQ', 'PPLW', 'PPLCH']);
const kept = cities
  .filter((c) => c.population >= minimum && c.featureCode.startsWith('PPL') && !excluded.has(c.featureCode) && !c.name.includes('|'))
  .sort((a, b) => b.population - a.population || (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
const lines = ['# name|country|admin|latitude|longitude|population. Generated by tools/cities.js from GeoNames (CC BY 4.0) via all-the-cities.'];
for (const c of kept) {
  const [lon, lat] = c.loc.coordinates;
  lines.push([c.name, c.country, c.adminCode || '', lat.toFixed(2), lon.toFixed(2), c.population].join('|'));
}
const out = path.join(__dirname, '..', 'res', 'raw', 'cities.txt');
fs.writeFileSync(out, lines.join('\n') + '\n');
console.log(out, kept.length, 'cities', Math.round(fs.statSync(out).size / 1024) + ' KB');
